export const makeI18n = (lang, setLang) => {
  const t = (key, vars) => {
    let s = DICT[lang]?.[key] ?? DICT.ceb[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
    return s;
  };
  // Kategorya: kung wala sa dictionary (custom), ipakita kung unsa kini.
  const catLabel = (c) => DICT[lang]?.['cat.' + c] ?? c;
  // Ngalan sa produkto: i-translate lang ang wala pa giusab nga pananglitan.
  const pname = (p) => {
    const seed = SEED_BY_ID[p.id];
    return lang === 'en' && seed && seed.name === p.name ? SEED_EN[p.id] : p.name;
  };
  return { lang, setLang, t, catLabel, pname };
};

export const LangContext = createContext(makeI18n('ceb', () => {}));
export const useI18n = () => useContext(LangContext);
